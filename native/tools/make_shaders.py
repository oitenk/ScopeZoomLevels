"""Compiles shaders/LensMask.hlsl to DXIL with the Windows SDK's dxc and writes
src/LensMaskDxil.h (the bytes, built into the plugin). Run: python -I tools/make_shaders.py"""
import os
import subprocess
import sys

DXC = r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe"
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "shaders", "LensMask.hlsl")
out = os.path.join(root, "build", "LensMask.dxil")
os.makedirs(os.path.dirname(out), exist_ok=True)
subprocess.run([DXC, "-nologo", "-T", "ps_6_0", "-E", "main", "-O3", src, "-Fo", out], check=True)
data = open(out, "rb").read()
if b"DXIL" not in data:
    sys.exit("dxc output has no DXIL part")
lines = [", ".join("0x%02x" % b for b in data[i : i + 16]) for i in range(0, len(data), 16)]
with open(os.path.join(root, "src", "LensMaskDxil.h"), "w") as f:
    f.write("// Generated by tools/make_shaders.py from shaders/LensMask.hlsl (DXIL, ps_6_0). Do not edit.\n")
    f.write("#pragma once\n\nconstexpr unsigned char kLensMaskDxil[] = {\n    ")
    f.write(",\n    ".join(lines))
    f.write("\n};\n")
print("LensMaskDxil.h:", len(data), "bytes")
