"""Builds the zoom-level patches and settings for every scope in tools/scopes.txt.

usage: python -I build_scopes.py <scopes.txt> <json dir> <patch out dir> <xl file> <tweak yaml>

scopes.txt: one scope per line, its model name (folder under base\\weapons\\firearms\\
attachments\\scope\\) followed by the magnification of each zoom level. A scope with no
levels is left out (no lens zoom). The word "no-vanilla" after the model drops the vanilla
level from that scope's cycle: aiming starts at its first zoom level.

<json dir> holds the scopes' vanilla .app and .mesh files as WolvenKit JSON (flat).
For each scope, every mesh with a lens material gets a patch mesh (JSON, under
<patch out dir>) and an entry in the ArchiveXL file, and the scope gets its settings
(lens parts and zoom levels) in the TweakXL file, in the same form other mods use.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # also under python -I
from build_mesh import add_levels  # noqa: E402

PATCH_ROOT = "scope_zoom_levels\\patches"
MESH_TYPES = ("entSkinnedMeshComponent", "entMeshComponent", "entGarmentSkinnedMeshComponent")


def read_scopes(path):
    """(model, magnifications, no vanilla level) per scope."""
    scopes = []
    for line in open(path, encoding="utf-8"):
        words = line.split("#")[0].split()
        if words:
            no_vanilla = "no-vanilla" in words[1:]
            levels = [float(w) for w in words[1:] if w != "no-vanilla"]
            scopes.append((words[0], levels, no_vanilla))
    return scopes


def components(app_doc):
    """(component name, mesh depot path) for every mesh component in every appearance."""
    found = []

    def walk(o):
        if isinstance(o, dict):
            if o.get("$type") in MESH_TYPES and "mesh" in o:
                found.append((o["name"]["$value"], o["mesh"]["DepotPath"]["$value"]))
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(app_doc["Data"]["RootChunk"]["appearances"])
    return found


def read_overrides(scopes_file):
    """tools/lens_overrides.json: per-scope lens material parameters (keys starting with _ are notes)."""
    path = os.path.join(os.path.dirname(scopes_file), "lens_overrides.json")
    if not os.path.exists(path):
        return {}
    data = json.load(open(path, encoding="utf-8"))

    def clean(o):
        return {k: clean(v) if isinstance(v, dict) else v for k, v in o.items() if not k.startswith("_")}

    return clean(data)


def main(scopes_file, json_dir, patch_dir, xl_file, yaml_file):
    patches = {}     # patch depot path -> target depot path
    settings = []    # (model, lens parts, magnifications, no vanilla level)
    overrides = read_overrides(scopes_file)
    for scope, levels, no_vanilla in read_scopes(scopes_file):
        if not levels:
            print(f"  {scope}: no levels, left out")
            continue
        app = json.load(open(os.path.join(json_dir, f"{scope}.app.json"), encoding="utf-8"))
        parts = components(app)
        lens_parts = set()
        for mesh in sorted({m for _, m in parts}):
            mesh_file = mesh.split("\\")[-1]
            src = os.path.join(json_dir, f"{mesh_file}.json")
            if not os.path.exists(src):
                print(f"  {scope}: {mesh_file} not extracted, skipped")
                continue
            doc = json.load(open(src, encoding="utf-8"))
            lenses = add_levels(doc, levels, overrides.get(scope))
            if not lenses:
                continue
            patch = f"{PATCH_ROOT}\\{mesh_file}"
            out = os.path.join(patch_dir, *patch.split("\\")) + ".json"
            os.makedirs(os.path.dirname(out), exist_ok=True)
            json.dump(doc, open(out, "w", encoding="utf-8"), indent=2)
            patches[patch] = mesh
            names = {n for n, m in parts if m == mesh}
            lens_parts |= names
            print(f"  {scope}: {mesh_file} lens {lenses}, levels {levels}, parts {sorted(names)}")
        if lens_parts:
            settings.append((scope, sorted(lens_parts), levels, no_vanilla))
        else:
            print(f"  {scope}: NO LENS MESH FOUND")

    with open(xl_file, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/build_scopes.py. Adds the lens zoom-level appearances (and their\n"
                "# lens materials) to the vanilla scope meshes at load time, instead of replacing them.\n")
        f.write("resource:\n  patch:\n")
        for patch, target in sorted(patches.items()):
            f.write(f"    {patch}:\n      - {target}\n")

    os.makedirs(os.path.dirname(yaml_file), exist_ok=True)
    with open(yaml_file, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/build_scopes.py from tools/scopes.txt.\n"
                "# Lens zoom levels per scope model (the item's appearanceResourceName), in the same\n"
                "# form other mods use for their own scopes. See README, \"For mod authors\".\n")
        for model, lens_parts, levels, no_vanilla in settings:
            f.write(f"\nScopeZoomLevels.{model}.lensParts: [ "
                    + ", ".join(f'n"{p}"' for p in lens_parts) + " ]\n")
            f.write(f"ScopeZoomLevels.{model}.zoomLevels: [ "
                    + ", ".join(repr(float(m)) for m in levels) + " ]\n")
            if no_vanilla:
                f.write(f"ScopeZoomLevels.{model}.noVanilla: true\n")
    print(f"{len(patches)} patch meshes, {len(settings)} scopes with lens zoom")


if __name__ == "__main__":
    main(*sys.argv[1:6])
